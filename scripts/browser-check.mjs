 assert.ok((await page.locator('.answer-text').innerText()).includes('快照'));check('真实问答 API 返回资料原文');
 await page.locator('.citation-card').first().click();
 await page.getByRole('dialog',{name:'状态快照',exact:true}).waitFor();
 assert.ok((await page.locator('.source-location').innerText()).includes('第 1 页'));check('引用定位到原文页码');
 await page.keyboard.press('Escape');
 await page.getByRole('textbox',{name:'输入学习问题'}).fill('火星地表矿物的同位素测定方法');
 await page.getByRole('button',{name:'发送问题',exact:true}).click();
