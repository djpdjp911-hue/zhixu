 await page.getByRole('button',{name:'学习诊断',exact:true}).click();
 await page.getByRole('button',{name:'开始第一组练习',exact:true}).click();
 const cards=page.locator('.quiz-card');assert.equal(await cards.count(),5);
 for(const card of await cards.all())await card.locator('.quiz-option').first().click();
 await page.getByRole('button',{name:'提交并生成复习任务'}).click();
 await page.getByText('本组练习已完成',{exact:true}).waitFor();
 assert.equal(await page.locator('.quiz-explanation').count(),5);check('诊断完成并展示依据');
 await page.getByRole('button',{name:'查看复习计划',exact:true}).click();
 assert.ok(await page.locator('.plan-task').count()>0);
 await page.locator('.task-check').first().click();
 assert.equal(await page.locator('.plan-task.done').count(),1);check('错题形成任务且可完成');
 await page.getByRole('button',{name:'我的资料',exact:false}).first().click();
 await page.getByRole('button',{name:'导入资料',exact:true}).click();
 await page.getByRole('textbox',{name:'资料名称',exact:true}).fill('端到端验证笔记');
 await page.getByRole('textbox',{name:'粘贴资料内容',exact:true}).fill('# 紫杉实验室\n\n## 特殊实验规则\n紫杉实验室的观测窗口设置为每日六点到七点。测试人员必须先校验蓝色传感器，再记录观测数据。观测结束后需要复核实验日志并关闭设备。');
 await page.getByRole('button',{name:'添加到资料库',exact:true}).click();
 await page.getByText('端到端验证笔记',{exact:true}).waitFor();check('导入自定义资料');
 await page.getByRole('button',{name:'证据问答',exact:true}).click();
 await page.getByRole('textbox',{name:'输入学习问题'}).fill('紫杉实验室的观测窗口设置为几点？');
 await page.getByRole('button',{name:'发送问题',exact:true}).click();
 await page.getByRole('heading',{name:'知序 · 原文检索'}).waitFor();
 assert.ok((await page.locator('.answer-text').innerText()).includes('六点到七点'));check('新资料即时参与检索');
 await page.screenshot({path:'outputs/evidence-desktop.png',fullPage:true});
 await page.waitForTimeout(600);await page.reload({waitUntil:'networkidle'});
 await page.getByRole('button',{name:'我的资料',exact:false}).first().click();
 await page.getByText('端到端验证笔记',{exact:true}).waitFor();check('刷新后 IndexedDB 恢复资料');
