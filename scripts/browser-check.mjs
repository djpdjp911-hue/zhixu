 await page.getByRole('button',{name:'学习工作台',exact:true}).click();
 await page.screenshot({path:'outputs/dashboard-mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 for(const name of ['我的资料','证据问答','知识脉络','学习诊断','复习计划']){
   await page.getByRole('button',{name,exact:false}).first().click();
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),name+' overflow');
 }
 check('390px 下六个页面均无横向溢出');
 assert.deepEqual(errors,[]);check('浏览器无未捕获错误');
 const result={runAt:new Date().toISOString(),base,checks,errors,passed:true};await writeFile('outputs/browser-check.json',JSON.stringify(result,null,2));
